#!/usr/bin/env python3
"""Write edaml_config.yaml into every released model condition.

    python3 tools/write_edaml_configs.py            # all conditions
    python3 tools/write_edaml_configs.py --check    # report only, write nothing

For model-data/<task>_prediction/<exp>/<pdk>-<stage>/ it combines

  * problem_formulation  -- the folder address + pj/<task>/settings.py (TARGET,
                            BASELINE, FINAL_STAGE)
  * network_architecture -- features and layers from the run's own hparams.yaml
                            (what was actually trained), with every Linear shape
                            checked against the trained checkpoint
  * hyperparameters      -- from the run's hparams.yaml
  * data                 -- the run's sampling_frac / parameter_config_ids (flow.log)
  * evaluation           -- the LOCO circuit list (flow.log)

into the executable-configuration layout of the EDA-OpenML paper (Listing 1,
Table 4). It refuses to write a config whose layers disagree with the checkpoint.
"""
import argparse
import os
import re
import sys
import zipfile
from pathlib import Path

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import readers  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "model-data"
PJ = ROOT / "pj"

PDK_LABEL = {"nangate45": "NG45", "sky130hd": "SKY130", "ihp-sg13g2": "IHP130", "asap7": "ASAP7"}
ENTITY = {
    "total_area": "netlist", "total_power": "netlist", "total_wirelength": "netlist",
    "worst_arrival_time": "netlist", "worst_slack": "netlist", "total_negative_slack": "netlist",
    "interconnect_length": "interconnect",
    "timing_path_arrival_time": "timing_path", "timing_path_slack": "timing_path",
    "net_arc_delay": "net_arc", "cell_arc_delay": "cell_arc", "cell_arc_slew": "cell_arc",
}
HP_ORDER = ("learning_rate", "batch_size", "no_of_epochs", "loss", "optimizer", "weight_decay")
VERSION_RE = re.compile(r"^version_(\d+)$")


def settings(task):
    txt = (PJ / f"{task}_prediction" / "settings.py").read_text()
    get = lambda k: re.search(rf'^{k}\s*=\s*"([^"]+)"', txt, re.M)[1]  # noqa: E731
    return {"target": get("TARGET"), "baseline": get("BASELINE"), "target_stage": get("FINAL_STAGE")}


def flow_info(cdir):
    p = cdir / "flow.log"
    txt = p.read_text(errors="replace") if p.is_file() else ""
    m = lambda pat: (re.search(pat, txt) or [None, None])[1]  # noqa: E731
    circuits = m(r"circuits \(\d+\):\s*(.+)")
    ids = m(r"parameter_config_ids:\s*(\S+)")
    return {
        "config_yaml": m(r"config_yaml:\s*(\S+)"),
        "sampling_frac": float(m(r"sampling_frac:\s*([\d.]+)") or 1.0),
        # "default" (or no line) = no configuration subset, i.e. all generated configurations
        "parameter_config_ids": [int(x) for x in ids.split(",")] if ids and ids != "default" else None,
        "circuits": [c.strip() for c in circuits.split(",")] if circuits else None,
    }


def newest_version(fold):
    vs = [(int(x[1]), d) for d in fold.iterdir() if d.is_dir() and (x := VERSION_RE.match(d.name))]
    return max(vs)[1] if vs else None


def run_spec(cdir):
    """hparams.yaml of the run + linear shapes read from a trained checkpoint."""
    spec, shapes = None, None
    for fold in sorted(d for d in cdir.iterdir() if d.is_dir()):
        ver = newest_version(fold)
        if not ver:
            continue
        if spec is None and (ver / "hparams.yaml").is_file():
            spec = readers.load_spec(ver / "hparams.yaml")
        ck = ver / "checkpoints" / "last.ckpt"
        if spec and ck.is_file() and shapes is None:
            with zipfile.ZipFile(ck) as z:
                pre = next(n.split("/data/")[0] for n in z.namelist() if "/data/" in n)
                shapes = []
                for i, (fo, _) in enumerate(readers.linear_shapes(spec["layers"])):
                    w = z.getinfo(f"{pre}/data/{2 * i}").file_size // 4
                    shapes.append((fo, w // fo))
        if spec and shapes:
            break
    return spec, shapes


def flow_list(xs):
    return "[" + ", ".join(str(x) for x in xs) + "]"


def render(task, exp, pdk, stage, st, spec, shapes, fl):
    feats = spec["features"]
    n_feat = sum(len(v) for v in feats.values())
    lines = [
        "# EDA-OpenML executable configuration",
        f"# {exp} · {task} · {PDK_LABEL[pdk]} · {stage}",
        "# Generated by tools/write_edaml_configs.py from this run's hparams.yaml and flow.log",
        f"# (config: {fl['config_yaml'] or 'n/a'}); Linear shapes verified against the trained checkpoint.",
        "",
        "problem_formulation:",
        f"  pdk: {PDK_LABEL[pdk]}",
        f"  source_stage: {stage}",
        f"  target_stage: {st['target_stage']}",
        f"  target: {st['target']}",
        f"  target_entity: {ENTITY[task]}",
        f"  baseline: {st['baseline']}",
        f"  source_entities: {flow_list(feats.keys())}",
        "",
        "network_architecture:",
        "  features:",
    ]
    lines += [f"    {g}: {flow_list(ns)}" for g, ns in feats.items()]
    lines.append("  layers:")
    li = 0
    for layer in spec["layers"]:
        t = str(layer.get("type"))
        lines.append(f"    - type: {t}")
        if t.lower() == "linear":
            fo, fi = shapes[li] if shapes else (layer["out_features"], layer["in_features"])
            if li == 0 and fi != n_feat:
                raise ValueError(f"first Linear takes {fi} inputs but {n_feat} features are listed")
            lines += [f"      in_features: {fi}", f"      out_features: {fo}"]
            li += 1
        elif t.lower() == "dropout" and "p" in layer:
            lines.append(f"      p: {layer['p']}")
    hp = spec["hparams"]
    lines += ["", "hyperparameters:"]
    lines += [f"  {k}: {hp[k]}" for k in HP_ORDER if k in hp]
    lines += [f"  {k}: {v}" for k, v in hp.items() if k not in HP_ORDER]
    lines += ["", "data:", f"  sampling_frac: {fl['sampling_frac']}"]
    if fl["parameter_config_ids"]:
        lines.append(f"  parameter_config_ids: {flow_list(fl['parameter_config_ids'])}")
    lines += ["", "evaluation:", "  protocol: leave_one_circuit_out"]
    if fl["circuits"]:
        lines.append(f"  circuits: {flow_list(fl['circuits'])}")
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="report only, write nothing")
    a = ap.parse_args()
    written, fixed, problems = 0, 0, []
    for tdir in sorted(SRC.glob("*_prediction")):
        task = tdir.name[: -len("_prediction")]
        st = settings(task)
        for edir in sorted(d for d in tdir.iterdir() if d.is_dir() and d.name != "baseline"):
            for cdir in sorted(d for d in edir.iterdir() if d.is_dir()):
                pdk = next((p for p in PDK_LABEL if cdir.name.startswith(p + "-")), None)
                if not pdk:
                    continue
                stage = cdir.name[len(pdk) + 1:]
                where = f"{tdir.name}/{edir.name}/{cdir.name}"
                spec, shapes = run_spec(cdir)
                if not spec:
                    problems.append(f"{where}: no hparams.yaml")
                    continue
                declared = [(fo, fi) for fo, fi in readers.linear_shapes(spec["layers"])]
                if shapes and shapes != declared:
                    fixed += 1
                try:
                    text = render(task, edir.name, pdk, stage, st, spec, shapes, flow_info(cdir))
                except (ValueError, KeyError) as err:
                    problems.append(f"{where}: {err}")
                    continue
                if not shapes:
                    problems.append(f"{where}: no checkpoint, shapes taken from hparams.yaml")
                if not a.check:
                    (cdir / "edaml_config.yaml").write_text(text)
                written += 1
    print(f"{'would write' if a.check else 'wrote'} {written} edaml_config.yaml "
          f"({fixed} with Linear shapes corrected from the checkpoint)")
    for p in problems:
        print("  ", p)


if __name__ == "__main__":
    main()
